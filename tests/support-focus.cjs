const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const footer = fs.readFileSync(require('node:path').join(__dirname, '../footer.php'), 'utf8');
const source = footer.slice(footer.indexOf('var rhWaOpener'), footer.indexOf('function rhSendWa'));
let open = false;
let expanded;
let escape;
const document = { activeElement: null };
const control = () => ({ isConnected: true, focus() { document.activeElement = this; } });
const opener = control(), toggle = control(), message = control();
toggle.setAttribute = (_, value) => { expanded = value; };
const box = { classList: { contains: () => open, toggle: (_, value) => { open = value; } } };
document.getElementById = id => ({ 'rh-wa-box': box, 'rh-wa-toggle': toggle, 'rh-wa-msg': message })[id];
document.querySelector = () => ({ addEventListener: (_, handler) => { escape = handler; } });
const ctx = vm.createContext({ document });
vm.runInContext(source, ctx);
opener.focus();
ctx.rhToggleWa(false);
assert.equal(document.activeElement, opener, 'Closing an already closed panel must not steal focus');
ctx.rhToggleWa(true, opener);
assert.equal(document.activeElement, message);
assert.equal(expanded, 'true');
let stopped = false;
escape({ key: 'Escape', stopPropagation() { stopped = true; } });
assert.equal(stopped, true);
assert.equal(expanded, 'false');
assert.equal(document.activeElement, opener);
ctx.rhToggleWa(true, opener);
opener.isConnected = false;
ctx.rhToggleWa(false);
assert.equal(document.activeElement, toggle);
console.log('Support focus regression checks passed');
